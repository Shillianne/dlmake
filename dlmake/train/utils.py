def progress_factory(config: ProgressConfig):
    train_progress = config.train_progress
    model_progress = config.model_progress
    lr = config.lr
    norm = config.norm
    mfu = config.mfu
    time = config.time
    tok = config.tok
    eta = config.eta
    parameters: list[inspect.Parameter] = []

    if train_progress:
        parameters.append(inspect.Parameter("epoch", inspect.Parameter.KEYWORD_ONLY, annotation=int))
        parameters.append(inspect.Parameter("total_epochs", inspect.Parameter.KEYWORD_ONLY, annotation=int))
    if model_progress:
        parameters.append(inspect.Parameter("cur_model", inspect.Parameter.KEYWORD_ONLY, annotation=int))
        parameters.append(inspect.Parameter("total_models", inspect.Parameter.KEYWORD_ONLY, annotation=int))
    if lr:
        parameters.append(inspect.Parameter("lr", inspect.Parameter.KEYWORD_ONLY, annotation=float))
    if norm:
        parameters.append(inspect.Parameter("norm", inspect.Parameter.KEYWORD_ONLY, annotation=float))
    if mfu:
        parameters.append(inspect.Parameter("mfu", inspect.Parameter.KEYWORD_ONLY, annotation=float))
    if time:
        parameters.append(inspect.Parameter("time", inspect.Parameter.KEYWORD_ONLY, annotation=float))
        parameters.append(inspect.Parameter("scale", inspect.Parameter.KEYWORD_ONLY, annotation=int))
    if tok:
        parameters.append(inspect.Parameter("tokens", inspect.Parameter.KEYWORD_ONLY, annotation=float))
    if eta:
        parameters.append(inspect.Parameter("eta", inspect.Parameter.KEYWORD_ONLY, annotation=float))

    sig = inspect.Signature(parameters)

    def inner(loss: torch.Tensor | Number, acc: torch.Tensor, **kwargs):
        blocks = []
        if model_progress and "cur_model" in kwargs.keys() and "total_models" in kwargs.keys():
            blocks.append(f"[{kwargs['cur_model']}/{kwargs['total_models']}]")
        if train_progress and "epoch" in kwargs.keys() and "total_epochs" in kwargs.keys():
            blocks.append(f"[{kwargs['epoch']}/{kwargs['total_epochs']}]")
        blocks.append(f"Average Loss: {loss:.3f}")
        if "looping" in kwargs.keys() and kwargs["looping"]:
            s = "Average Loop Accuracies: ["
            for i, v in enumerate(acc):
                s += f"Loop {i + 1:>{len(str(len(acc)))}}: {v.item() * 100:.2f}%"
                if i < len(acc) - 1:
                    s += ", "
            s += "]"
            blocks.append(s)
        else:
            blocks.append(f"Average Accuracy: {(acc.item() * 100):.2f}%")
        if lr and "lr" in kwargs.keys():
            blocks.append(f"lr: {kwargs['lr']:.3e}")
        if norm and "norm" in kwargs.keys():
            blocks.append(f"Model Norm: {kwargs['norm']:.4f}")
        if mfu and "mfu" in kwargs.keys():
            blocks.append(f"MFU: {(kwargs['mfu'] * 100):.2f}%")
        if time and "time" in kwargs.keys() and "scale" in kwargs.keys():
            blocks.append(f"dt: {(kwargs['time'] * kwargs['scale']):.2f} {'s' if kwargs['scale'] == 1 else 'ms'}")
        if tok and "tokens" in kwargs.keys():
            blocks.append(f"tok/sec: {kwargs['tokens']:.2f}")
        if eta and "eta" in kwargs.keys():
            time_format = str(timedelta(seconds=kwargs['eta']))
            d, h, m, s = "", "", "", ""
            if "day" in time_format:
                d = time_format.split(", ")[0].split(" ")[0]
                h, m, s = time_format.split(", ")[1].split(":")
                m, s = m.lstrip('0'), s.lstrip('0')
            else:
                h, m, s = time_format.split(":")
            blocks.append(f"ETA: {'' if d == '' else d + ' days '}{h} h {m} min {s} s")
        return " | ".join(blocks)

    inner.__annotations__ = {param.name: param.annotation for param in parameters if param.annotation}
    return inner

class SaveOptions:
    readme_blueprint = (
        "# Configuration for the model\n"\
        "\n"\
        "> The following contents are automatically generated by the training of a model.\n"\
        "Configuration used for training the model:\n\n"\
        "| Attribute | Value |\n"\
        "|-----------|-------|\n"\
        "<0:table:2>\n"\
        "\n"\
        "With the previous training parameters, the final model size for training was <0> parameters.\n"\
        "As of writing this file (iteration <1>/<2>), these are the obtained results:\n"\
        "| Training Loss | Validation Loss | Training Accuracy | Validation Accuracy |\n"\
        "|---------------|-----------------|-------------------|---------------------|\n"\
        "<1:table:4>\n"\
        "The final results obtained can be viewed with the following image:\n\n"\
        "<0:img>\n\n"
    )
    def __init__(self, savepath: str, config: Config, onnx: bool = False) -> None:
        if not os.path.exists(savepath):
            os.mkdir(savepath)
        h = hash(config)
        if not os.path.exists(os.path.join(savepath, str(h))):
            os.mkdir(os.path.join(savepath, str(h)))
        if config.training.save_history:
            os.mkdir(os.path.join(savepath, str(h), "history"))
        self.savepath = os.path.join(savepath, str(h))
        self.onnx = onnx
        self.history = config.training.save_history
        self.saves = 0

    @staticmethod
    def replace_template(template: str, data: dict, final: bool = False):
        tables: list[str] = re.findall(r'<[0-9]*:table:[0-9]*>', template)
        for table in tables:
            rows = ""
            head = table.replace('<', '').replace('>', '')
            index, _, columns = head.split(':')
            index, columns = int(index), int(columns)
            assert len(data["table"]) - 1 >= index, "Provided values (table) do not match the expected information on the template"
            for items in data["table"][index]:
                if len(items) != columns:
                    raise ValueError(f"Wrong number of elements for {columns} columns. Got {len(items)}")
                rows += "| " + " | ".join([str(v) for v in items]) + " |\n"
            template = template.replace(table, rows)
        numbers: list[str] = re.findall(r'<[0-9]*>', template)
        for number in numbers:
            index = int(number.replace('<', '').replace('>', ''))
            assert len(data["number"]) >= index, "Provided values (number) do not match the expected information on the template"
            template = template.replace(number, str(data["number"][index]))
        if final:
            images: list[str] = re.findall(r'<[0-9]*:img>', template)
            for image in images:
                index = int(image.replace('<', '').replace('>', '').split(':')[0])
                assert len(data["img"]) >= index, "Provided values (image) do not match the expected information on the template"
                text, path = *list(data["img"][index].keys()), *list(data["img"][index].values())
                template = template.replace(image, f"![{text}]({path})")
        return template

    def save_image(self, trainer):
        fig, axes = plt.subplots(1, 2, figsize=(18, 8))
        axes[0].plot(torch.arange(0, len(trainer.loss_history)), [t.cpu() for t in trainer.loss_history], label="Training Loss", c="royalblue")
        if trainer.config.training.val_rate is not None:
            axes[0].plot(torch.arange(0, trainer.max_epochs, trainer.config.training.val_rate - 1), [t.cpu() for t in trainer.val_loss], label="Validation Loss", c="orangered")
        axes[0].set_title("Loss over time")
        axes[0].set_xlabel("Epochs")
        axes[0].set_ylabel("Loss")
        axes[0].legend()
        axes[1].plot(torch.arange(0, len(trainer.acc_history)), [t.cpu() for t in trainer.acc_history], label="Training Accuracy", c="royalblue")
        if trainer.config.training.val_rate is not None:
            axes[1].plot(torch.arange(0, trainer.max_epochs, trainer.config.training.val_rate - 1), [t.cpu() for t in trainer.val_acc], label="Validation Accuracy", c="orangered")
        axes[1].set_title("Accuracy over time")
        axes[1].set_xlabel("Epochs")
        axes[1].set_ylabel("Accuracy")
        axes[1].legend()
        fig.savefig(os.path.join(self.savepath, "results.png"))


    def save(self, model: Transformer, trainer, epoch: int):
        meta = {}
        meta['EPOCHS_RUN'] = epoch + 1
        if trainer.config.training.use_val:
            meta["LOADER"] = {
                "train": trainer.train_dataloader.__dict__,
                "test": trainer.test_dataloader.__dict__,
                "val": trainer.val_dataloader.__dict__,
            }
            meta["VAL_LOSS"] = trainer.val_loss
            meta["VAL_ACC"] = trainer.val_acc
        else:
            meta["LOADER"] = {
                "train": trainer.train_dataloader.__dict__,
                "test": trainer.test_dataloader.__dict__,
            }
        meta["OPTIM"] = trainer.optimizer.state_dict()
        meta["CONFIG"] = {k: v for k, v in trainer.config.__dict__.items() if not k.startswith('_')}
        meta["L_HISTORY"] = trainer.loss_history
        meta["A_HISTORY"] = trainer.acc_history
        meta["N_HISTORY"] = trainer.norm_history
        meta["TEST_LOSS"] = trainer.test_loss
        meta["TEST_ACC"] = trainer.test_acc
        for benchmark in trainer.benchmarks:
            meta[f"{benchmark}_ACC".upper()] = getattr(self, f'{benchmark}_acc')
        if self.onnx:
            x = torch.randint(0, 1968, (trainer.config.batch_size, trainer.config.ctx_size), dtype=torch.long) 
            ix = torch.randint(0, 65, (trainer.config.batch_size, trainer.config.ctx_size), dtype=torch.long)
            px = torch.randint(0, 65, (trainer.config.batch_size, trainer.config.ctx_size), dtype=torch.long)
            torch.onnx.export(
                model,
                (x, ix, px),
                os.path.join(self.savepath, "snapshot.onnx"),
                input_names=["x", "ix", "px"],
                dynamo=True
            )
        else:
            if not self.history:
                torch.save(model.state_dict(), os.path.join(self.savepath, 'snapshot.pth'))
            else:
                torch.save(model.state_dict(), os.path.join(self.savepath, "history", f"snapshot_{self.saves:>03}.pth"))
                self.saves += 1
        torch.save(meta, os.path.join(self.savepath, 'metadata.pth'))
        data = {
            "table": [
                [(k, v) for k, v in trainer.config.__dict__.items()],
                [[round(array[-1].item(), 3) for array in [trainer.loss_history, trainer.test_loss, trainer.acc_history, trainer.test_acc]]]
            ],
            "number": [
                sum(p.numel() for p in model.parameters() if p.requires_grad),
                epoch + 1,
                trainer.max_epochs
            ],
            "img": [
                {"Loss and accuracy results from training": "results.png"}
            ]
        }
        final = False
        if trainer.max_epochs - 1 == epoch:
            self.save_image(trainer)
            final = True
        content = self.replace_template(SaveOptions.readme_blueprint, data, final)
        with open(os.path.join(self.savepath, "README.md"), "w") as f:
            f.write(content)
        trainer.logger("Saved snapshot of the model.")

    def load(self, trainer):
        snapshot = torch.load(os.path.join(self.savepath, 'snapshot.pth'))
        meta = torch.load(os.path.join(self.savepath, 'metadata.pth'))
        trainer.model.inner.load_state_dict(snapshot)
        trainer.model.inner.to(trainer.device)
        if trainer.compile:
            trainer.logger("Starting model compilation...")
            trainer.model.inner = cast(Transformer, torch.compile(trainer.model.inner))
            trainer.logger("Finished model compilation")
        if trainer.ddp:
            ddp_holder = DDP(trainer.model.inner, device_ids=[trainer.ddp_local_rank])
            trainer.model.inner = cast(Transformer, ddp_holder.module)

        trainer.step = meta["EPOCHS_RUN"]
        loader_settings: dict[str, dict] = meta["LOADER"]
        optim_state_dict = meta["OPTIM"]
        trainer.loss_history = meta["L_HISTORY"]
        trainer.acc_history = meta["A_HISTORY"]
        trainer.norm_history = meta["N_HISTORY"]
        trainer.test_loss = meta["TEST_LOSS"]
        trainer.test_acc = meta["TEST_ACC"]
        trainer.optimizer = trainer.model.inner.configure_parameters(weight_decay=0.1, lr=6e-4, device=trainer.device)
        trainer.optimizer.load_state_dict(optim_state_dict)

        for benchmark in trainer.benchmarks:
            setattr(trainer, f'{benchmark}_acc', meta[f'{benchmark}_ACC'.upper()])

        trainer.train_dataloader.resume(**loader_settings['train'])
        trainer.test_dataloader.resume(**loader_settings["test"])
        if trainer.config.training.use_val:
            trainer.val_dataloader.resume(**loader_settings['val'])
            trainer.val_loss = meta["VAL_LOSS"]
            trainer.val_acc = meta["VAL_ACC"]
        trainer.logger("Loaded snapshot of the model.")


class Logger:
    def __init__(self, filename: str, new: bool = True):
        self.testing = int(os.environ.get("DLMAKE_TESTING", -1)) != -1
        self.filename = filename
        if new and not self.testing:
            with open(filename, "w") as _:
                pass

    def log(self, msg: str):
        if not self.testing:
            with open(self.filename, "a") as f:
                f.write(msg + "\n")
        print(msg)

    def warn(self, msg: str):
        if not self.testing:
            with open(self.filename, "a") as f:
                f.write("Warning: " + msg + "\n")
        print("\033[93m" + "Warning: " + msg + "\033[0m")

    def error(self, msg: str):
        if not self.testing:
            with open(self.filename, "a") as f:
                f.write("Warning: " + msg + "\n")
        print("\033[91m" + "Error: " + msg + "\033[0m")
