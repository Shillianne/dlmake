class SaveOptions:
    readme_blueprint = (
        "# Configuration for the model\n"\
        "\n"\
        "> The following contents are automatically generated by the training of a model.\n"\
        "Configuration used for training the model:\n\n"\
        "| Attribute | Value |\n"\
        "|-----------|-------|\n"\
        "<0:table:2>\n"\
        "\n"\
        "With the previous training parameters, the final model size for training was <0> parameters.\n"\
        "As of writing this file (iteration <1>/<2>), these are the obtained results:\n"\
        "| Training Loss | Validation Loss | Training Accuracy | Validation Accuracy |\n"\
        "|---------------|-----------------|-------------------|---------------------|\n"\
        "<1:table:4>\n"\
        "The final results obtained can be viewed with the following image:\n\n"\
        "<0:img>\n\n"
    )
    def __init__(self, savepath: str, config: Config, onnx: bool = False) -> None:
        if not os.path.exists(savepath):
            os.mkdir(savepath)
        h = hash(config)
        if not os.path.exists(os.path.join(savepath, str(h))):
            os.mkdir(os.path.join(savepath, str(h)))
        self.savepath = os.path.join(savepath, str(h))
        self.onnx = onnx

    @staticmethod
    def replace_template(template: str, data: dict, final: bool = False):
        tables: list[str] = re.findall(r'<[0-9]*:table:[0-9]*>', template)
        for table in tables:
            rows = ""
            head = table.replace('<', '').replace('>', '')
            index, _, columns = head.split(':')
            index, columns = int(index), int(columns)
            assert len(data["table"]) - 1 >= index, "Provided values (table) do not match the expected information on the template"
            for items in data["table"][index]:
                if len(items) != columns:
                    raise ValueError(f"Wrong number of elements for {columns} columns. Got {len(items)}")
                rows += "| " + " | ".join([str(v) for v in items]) + " |\n"
            template = template.replace(table, rows)
        numbers: list[str] = re.findall(r'<[0-9]*>', template)
        for number in numbers:
            index = int(number.replace('<', '').replace('>', ''))
            assert len(data["number"]) >= index, "Provided values (number) do not match the expected information on the template"
            template = template.replace(number, str(data["number"][index]))
        if final:
            images: list[str] = re.findall(r'<[0-9]*:img>', template)
            for image in images:
                index = int(image.replace('<', '').replace('>', '').split(':')[0])
                assert len(data["img"]) >= index, "Provided values (image) do not match the expected information on the template"
                text, path = *list(data["img"][index].keys()), *list(data["img"][index].values())
                template = template.replace(image, f"![{text}]({path})")
        return template

    def save_image(self, trainer: "Trainer"):
        fig, axes = plt.subplots(1, 2, figsize=(18, 8))
        axes[0].plot(torch.arange(0, len(trainer.loss_history)), trainer.loss_history, label="Training Loss", c="royalblue")
        axes[0].plot(torch.arange(0, len(trainer.val_loss)), trainer.val_loss, label="Validation Loss", c="orangered")
        axes[0].set_title("Loss over time")
        axes[0].set_xlabel("Epochs")
        axes[0].set_ylabel("Loss")
        axes[0].legend()
        axes[1].plot(torch.arange(0, len(trainer.acc_history)), trainer.acc_history, label="Training Accuracy", c="royalblue")
        axes[1].plot(torch.arange(0, len(trainer.val_acc)), trainer.val_acc, label="Validation Accuracy", c="orangered")
        axes[1].set_title("Accuracy over time")
        axes[1].set_xlabel("Epochs")
        axes[1].set_ylabel("Accuracy")
        axes[1].legend()
        fig.savefig(os.path.join(self.savepath, "results.png"))


    def save(self, model: Transformer, trainer: "Trainer", epoch: int):
        meta = {}
        meta['EPOCHS_RUN'] = epoch + 1
        if trainer.config.use_val:
            meta["LOADER"] = {
                "train": {
                    "iterations": trainer.train_loader.iterations,
                    "current_position": trainer.train_loader.current_position,
                    "current_shard": trainer.train_loader.current_shard
                },
                "valid": {
                    "iterations": trainer.val_loader.iterations,
                    "current_position": trainer.val_loader.current_position,
                    "current_shard": trainer.val_loader.current_shard
                }
            }
        else:
            meta["LOADER"] = {
                "train": {
                    "iterations": trainer.train_loader.iterations,
                    "current_position": trainer.train_loader.current_position,
                    "current_shard": trainer.train_loader.current_shard
                }
            }
        meta["OPTIM"] = trainer.optimizer.state_dict()
        meta["CONFIG"] = {k: v for k, v in trainer.config.__dict__.items() if not k.startswith('_')}
        meta["L_HISTORY"] = trainer.loss_history
        meta["A_HISTORY"] = trainer.acc_history
        meta["N_HISTORY"] = trainer.norm_history
        meta["VAL_LOSS"] = trainer.val_loss
        meta["VAL_ACC"] = trainer.val_acc
        for benchmark in trainer.benchmarks:
            meta[f"{benchmark}_ACC".upper()] = getattr(self, f'{benchmark}_acc')
        if self.onnx:
            x = torch.randint(0, 1968, (trainer.config.batch_size, trainer.config.ctx_size), dtype=torch.long) 
            ix = torch.randint(0, 65, (trainer.config.batch_size, trainer.config.ctx_size), dtype=torch.long)
            px = torch.randint(0, 65, (trainer.config.batch_size, trainer.config.ctx_size), dtype=torch.long)
            torch.onnx.export(
                model,
                (x, ix, px),
                os.path.join(self.savepath, "snapshot.onnx"),
                input_names=["x", "ix", "px"],
                dynamo=True
            )
        else:
            torch.save(model.state_dict(), os.path.join(self.savepath, 'snapshot.pth'))
        torch.save(meta, os.path.join(self.savepath, 'metadata.pth'))
        data = {
            "table": [
                [(k, v) for k, v in trainer.config.__dict__.items()],
                [[round(array[-1].item(), 3) for array in [trainer.loss_history, trainer.val_loss, trainer.acc_history, trainer.val_acc]]]
            ],
            "number": [
                sum(p.numel() for p in model.parameters() if p.requires_grad),
                epoch + 1,
                trainer.max_epochs
            ],
            "img": [
                {"Loss and accuracy results from training": os.path.join(self.savepath, "results.png")}
            ]
        }
        final = False
        if trainer.max_epochs - 1 == epoch:
            self.save_image(trainer)
            final = True
        content = self.replace_template(SaveOptions.readme_blueprint, data, final)
        with open(os.path.join(self.savepath, "README.md"), "w") as f:
            f.write(content)
        trainer.logger("Saved snapshot of the model.")

    def load(self, trainer: "Trainer"):
        snapshot = torch.load(os.path.join(self.savepath, 'snapshot.pth'))
        meta = torch.load(os.path.join(self.savepath, 'metadata.pth'))
        trainer.model.load_state_dict(snapshot)
        trainer.model.to(trainer.device)
        if trainer.compile:
            trainer.logger("Starting model compilation...")
            trainer.model = cast(Transformer, torch.compile(trainer.model))
            trainer.logger("Finished model compilation")
        if trainer.ddp:
            ddp_holder = DDP(trainer.model, device_ids=[trainer.ddp_local_rank])
            trainer.model = cast(Transformer, ddp_holder.module)

        trainer.step = meta["EPOCHS_RUN"]
        loader_settings: Dict[str, Dict] = meta["LOADER"]
        optim_state_dict = meta["OPTIM"]
        trainer.loss_history = meta["L_HISTORY"]
        trainer.acc_history = meta["A_HISTORY"]
        trainer.norm_history = meta["N_HISTORY"]
        trainer.val_loss = meta["VAL_LOSS"]
        trainer.val_acc = meta["VAL_ACC"]
        trainer.optimizer = trainer.model.configure_parameters(weight_decay=0.1, lr=6e-4, device=trainer.device)
        trainer.optimizer.load_state_dict(optim_state_dict)

        for benchmark in trainer.benchmarks:
            setattr(trainer, f'{benchmark}_acc', meta[f'{benchmark}_ACC'.upper()])

        trainer.train_loader.resume(*list(loader_settings['train'].values()))
        if trainer.config.use_val:
            trainer.val_loader.resume(*list(loader_settings['valid'].values()))
        trainer.logger("Loaded snapshot of the model.")

class Trainer:
    def __init__(self,
                 model: Transformer,
                 dataloader: Type[BaseDataLoader],
                 config: Config,
                 savepath: str,
                 lr_schedule: Callable,
                 benchmarks: List[Benchmark],
                 step: int = 0,
                 tokens_per_batch: int = 0,
                 logger: Optional[Logger] = None)-> None:

        num_classes = config.vocab_size
        T = config.ctx_size

        self.ddp = int(os.environ.get("RANK", -1)) != -1
        self.config = config
        self.benchmarks = benchmarks
        self.lr_scheduler: Callable = lr_schedule
        self.verbose = config.verbose
        self.batch_size = config.batch_size
        self.validation_rate = self.config.validation_rate if self.config.validation_rate is not None else 100
        self.benchmark_rate = (self.config.benchmark_rate if self.config.benchmark_rate is not None else 100) if self.benchmarks else 0
        self.logger = logger.log if logger is not None else (lambda x: print(x))
        self.loss_history: list[torch.Tensor] = []
        self.acc_history: list[torch.Tensor] = []
        self.norm_history: list[torch.Tensor] = []
        self.val_loss: list[torch.Tensor] = []
        self.val_acc: list[torch.Tensor] = []
        for benchmark in self.benchmarks:
            setattr(self, f"{benchmark}_acc", [])
        self.t = 1
        assert "reset" in dir(dataloader), "Provided dataloader needs to have a reset method"
        assert "split" in inspect.getfullargspec(dataloader).args, "The dataloader class needs to produce different loaders for training and validation."
        self.t = 1000 if config.time_precision == "ms" else 1
        self.compile = config.compile
        assert isinstance(self.compile, bool) and isinstance(self.config.new, bool), 'Compile and New have to be boolean arguments'

        if self.ddp:
            assert torch.cuda.is_available(), 'Cannot run DDP on CPU'
            init_process_group(backend='nccl')
            self.ddp_rank = int(os.environ['RANK'])
            self.ddp_local_rank = int(os.environ['LOCAL_RANK'])
            self.ddp_world_size = int(os.environ['WORLD_SIZE'])
            self.device = f"cuda:{self.ddp_local_rank}"
            torch.cuda.set_device(self.device)
            self.master_process = self.ddp_rank == 0
        else:
            self.ddp_rank = 0
            self.ddp_local_rank = 0
            self.ddp_world_size = 1
            self.master_process = True
            self.device = 'cpu'
            if torch.cuda.is_available():
                self.device = 'cuda'
            elif hasattr(torch.backends, 'mps') and torch.backends.mps.is_available():
                self.device = 'mps'
            self.logger(f"Using device: {self.device}")

        self.train_loader = dataloader(batch_size=config.batch_size,
                                       context_size=T,
                                       epoch_batch_size=tokens_per_batch,
                                       split='train',
                                       rank=self.ddp_rank,
                                       world_size=self.ddp_world_size)
        if self.config.use_val:
            self.val_loader = dataloader(batch_size=config.batch_size,
                                         context_size=T,
                                         epoch_batch_size=tokens_per_batch,
                                         split='val',
                                         rank=self.ddp_rank,
                                         world_size=self.ddp_world_size)
        self.model = model
        self.save_options = SaveOptions(savepath, config, False)
        if os.path.exists(os.path.join(self.save_options.savepath, 'snapshot.pth')) and not self.config.new:
            self.save_options.load(self)
        else:
            self.model.to(self.device)
            if self.compile:
                self.logger("Starting model compilation...")
                self.model = cast(Transformer, torch.compile(self.model))
                self.logger("Finished model compilation")
            if self.ddp:
                ddp_holder = DDP(self.model, device_ids=[self.ddp_local_rank])
                self.model = cast(Transformer, ddp_holder.module)
            self.optimizer = self.model.configure_parameters(weight_decay=0.1, lr=6e4, device=self.device)
            self.step = step
        self.loss_fn = nn.CrossEntropyLoss()
        self.accuracy = Accuracy(task='multiclass', num_classes=num_classes)
        self.accuracy.to(self.device)

    def train(self, epochs: int) -> None:
        assert epochs >= self.config.checkpoint_rate
        assert self.step < epochs, "Training was already completed for the requested number of epochs"
        self.max_epochs = epochs
        running_mfu = -1.0

        for epoch in range(epochs):
            start = time.time()
            last_epoch = (epoch == epochs - 1)

            if (epoch % self.validation_rate == 0 or last_epoch) and self.config.use_val:
                self.model.eval()
                self.val_loader.reset()
                with torch.inference_mode():
                    val_loss = torch.tensor(0., device=self.device)
                    val_acc = torch.tensor(0., device=self.device)
                    i = 0
                    for i, data in enumerate(self.val_loader):
                        gpu_data = [v.to(self.device) for v in data]
                        with torch.autocast(device_type=self.device, dtype=torch.bfloat16):
                            logits: torch.Tensor = self.model(*gpu_data[:-1])
                            loss: torch.Tensor = self.loss_fn(logits.view(-1, logits.shape[-1]), gpu_data[-1].view(-1))
                            # self.logger(f"{logits}")
                        loss = loss / self.val_loader.limit
                        acc: torch.Tensor = self.accuracy(logits.view(-1, logits.shape[-1]), gpu_data[-1].view(-1))
                        val_loss += loss.detach()
                        val_acc += acc.detach()
                    val_acc /= (i + 1)
                    self.val_loss.append(val_loss)
                    self.val_acc.append(val_acc)
                    if self.ddp:
                        dist.all_reduce(val_loss, op=dist.ReduceOp.AVG)
                    if self.master_process:
                        self.logger(f"Validation loss: {val_loss.item():.3f} | Validation accuracy: {(val_acc.item() * 100):.3f}%")

            # if self.benchmarks and (epoch % self.benchmark_rate == 0 or last_epoch):
            #     self._validate_benchmarks()

            losses = torch.tensor(0., device=self.device)
            accs = torch.tensor(0., device=self.device)
            total = 0
            self.model.train()
            self.optimizer.zero_grad()

            for i, data in enumerate(self.train_loader):
                gpu_data = [v.to(self.device) for v in data]
                if self.ddp:
                    setattr(self.model, "require_backward_grad_sync", (i == self.train_loader.limit - 1))
                with torch.autocast(device_type=self.device, dtype=torch.bfloat16):
                    y_preds: torch.Tensor = self.model(*gpu_data[:-1])
                    loss: torch.Tensor = self.loss_fn(y_preds.view(-1, y_preds.shape[-1]), gpu_data[-1].view(-1))
                loss = loss / self.train_loader.limit
                losses += loss.detach()
                acc: torch.Tensor = self.accuracy(y_preds.view(-1, y_preds.shape[-1]), gpu_data[-1].view(-1))
                accs += acc.detach()
                loss.backward()
                total = i
            if self.ddp:
                dist.all_reduce(losses, op=dist.ReduceOp.AVG)
            norm = nn.utils.clip_grad_norm_(self.model.parameters(), 1.0)
            lr = self.lr_scheduler(epoch)
            for param_group in self.optimizer.param_groups:
                param_group['lr'] = lr
            self.optimizer.step()
            torch.cuda.synchronize()
            end = time.time()
            dt = end - start
            tok_per_sec = (self.train_loader.B * self.train_loader.T * self.train_loader.limit * self.ddp_world_size) / dt
            mfu = self.model.estimate_mfu(self.batch_size * self.train_loader.limit, dt)
            running_mfu = mfu if running_mfu == -1.0 else 0.9 * running_mfu + 0.1 * mfu

            accs /= (total + 1)
            if self.verbose and self.master_process:
                self.logger(f"[{epoch + 1}/{epochs}] | Average Loss: {losses:.3f} | Average Accuracy: {(accs * 100):.2f}% | lr: {lr:.3e} | Model Norm: {norm:.4f}"\
                      f" | MFU: {running_mfu * 100:.2f}% | dt: {(dt * self.t):.2f} {'s' if self.t == 1 else 'ms'} | tok/sec: {tok_per_sec:.2f}")
            self.loss_history.append(losses)
            self.acc_history.append(accs)
            self.norm_history.append(norm)
            
            if epoch % self.config.checkpoint_rate == 0 and self.master_process:
                self.save_options.save(self.model, self, epoch)
        if self.master_process:
            self.save_options.save(self.model, self, epochs - 1)
        if self.ddp:
            destroy_process_group()

    def _validate_benchmarks(self):
        num_correct_norm = 0
        num_total = 0
        results = {}
        for benchmark in self.benchmarks:
            for i, example in enumerate(benchmark.iterate()):
                if i % self.ddp_world_size != self.ddp_rank:
                    continue
                _, tokens, mask, label = example
                tokens = tokens.to(self.device)
                mask = mask.to(self.device)
                with torch.inference_mode():
                    with torch.autocast(device_type=self.device, dtype=torch.bfloat16):
                        logits: torch.Tensor = self.model(tokens)
                    pred_norm = get_most_likely_row(tokens, mask, logits)
                num_total += 1
                num_correct_norm += int(pred_norm == label)
            if self.ddp:
                num_total = torch.tensor(num_total, dtype=torch.long, device=self.device)
                num_correct_norm = torch.tensor(num_correct_norm, dtype=torch.long, device=self.device)
                dist.all_reduce(num_total, op=dist.ReduceOp.SUM)
                dist.all_reduce(num_correct_norm, op=dist.ReduceOp.SUM)
                num_total = num_total.item()
                num_correct_norm = num_correct_norm.item()
            acc_norm = num_correct_norm / num_total
            results[benchmark.name] = acc_norm
        s = []
        for benchmark, acc in results.items():
            s.append(f"{benchmark} Accuracy: {(acc * 100):.4f}%")
            benchmark_acc: list = getattr(self, f"{benchmark}_acc")
            benchmark_acc.append(acc)
            setattr(self, f"{benchmark}_acc", benchmark_acc)
        if self.master_process:
            self.logger(" | ".join(s))

